const {candidateLimiter}=require('../../middlewares/rate-limit.middleware');
const express = require('express');
const { authenticate, requireAdmin, requireRole } = require('../../middlewares/auth.middleware');
const controller = require('./exam-rounds.controller');
const adminRouter = express.Router();
adminRouter.use(authenticate, requireAdmin);
const structure=require('./structure.controller');
adminRouter.get('/:id/structure',structure.get);
adminRouter.put('/:id/structure',structure.save);
adminRouter.post('/:id/structure/preview',structure.preview);
const reports = require('../reports/reports.controller');
adminRouter.use('/:id/questions', require('../questions/questions.routes'));
adminRouter.get('/:id/committee-statistics', reports.committees);
adminRouter.get('/:id/participants/:userId/attempts', require('../attempts/attempts.admin.controller').history);
adminRouter.get('/:id/results', reports.results);
adminRouter.get('/:id/statistics', reports.statistics);
adminRouter.get('/:id/question-statistics', reports.questions);
adminRouter.get('/:id/export', reports.export);
adminRouter.delete('/:id/trial-data', require('../attempts/attempts.controller').clearTrialData);
adminRouter.get('/', controller.adminList);
adminRouter.get('/:id', controller.adminGet);
adminRouter.post('/', controller.create);
adminRouter.patch('/:id', controller.update);
adminRouter.put('/:id', controller.update);
adminRouter.delete('/:id', controller.remove);
const userRouter = express.Router();
userRouter.use(authenticate, candidateLimiter);
userRouter.post('/:id/start', requireRole('USER'), require('../attempts/attempts.controller').start);
userRouter.get('/', controller.list);
userRouter.get('/:id', controller.get);
module.exports = { adminRouter, userRouter };
